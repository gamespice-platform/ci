#!/usr/bin/env python3
"""Write the GameSpice addon index: one file listing every addon, what it is for and the
classes it gives a game to extend, so an agent checks it before writing code into a game.

    scripts/addons-index.py [--root DIR] [--out FILE]   (defaults: ~/godot, <root>/ADDONS.md)

An addon is a dot-* checkout in DIR (symlinked aliases skipped) with addons/<x>/plugin.cfg.
Per addon: the plugin.cfg description, the API level (<x>_api.gd LEVEL, the floor a game
puts in requires.floor.json) and every class_name under addons/ with its first ## doc line.
"""
import argparse
import os
import re
import subprocess

CLASS = re.compile(r"^class_name\s+(\w+)", re.M)
DESC = re.compile(r'^description="(.*)"\s*$', re.M)
LEVEL = re.compile(r"^const LEVEL\s*:?=\s*(\d+)", re.M)


def first_doc(text, at):
    """The first ## line before or after the class_name (Godot doc comment)."""
    for ln in text[:at].split("\n")[::-1][:6] + text[at:].split("\n")[1:8]:
        s = ln.strip()
        if s.startswith("##"):
            return s.lstrip("#").strip()
    return ""


def addon(root, name):
    d = os.path.join(root, name)
    r = subprocess.run(["git", "-C", d, "ls-files", "--", "addons/"], capture_output=True, text=True)
    files = [f for f in r.stdout.split("\n") if f]
    cfgs = [f for f in files if f.endswith("/plugin.cfg") and f.count("/") == 2]
    if not cfgs:
        return None
    desc, level, classes = "", "", []
    for c in cfgs:
        m = DESC.search(open(os.path.join(d, c), encoding="utf-8", errors="replace").read())
        desc = desc or (m.group(1).replace('\\"', '"') if m else "")
    for f in files:
        if not f.endswith(".gd") or "/tests/" in f:
            continue
        t = open(os.path.join(d, f), encoding="utf-8", errors="replace").read()
        if f.endswith("_api.gd") and not level:
            m = LEVEL.search(t)
            level = m.group(1) if m else ""
        m = CLASS.search(t)
        if m:
            classes.append((m.group(1), f, first_doc(t, m.start())))
    return {"name": name, "dir": cfgs[0].split("/")[1], "desc": desc, "level": level, "classes": sorted(classes)}


def main():
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--root", default=os.path.expanduser("~/godot"))
    p.add_argument("--out")
    a = p.parse_args()
    out = a.out or os.path.join(a.root, "ADDONS.md")
    rows = []
    for n in sorted(os.listdir(a.root)):
        if n.startswith("dot-") and not os.path.islink(os.path.join(a.root, n)):
            x = addon(a.root, n)
            if x:
                rows.append(x)
    w = ["# GameSpice addons index",
         "",
         "Generated by dot-ci/scripts/addons-index.py; regenerate, do not edit. %d addons." % len(rows),
         "",
         "**Check here before writing code into a game.** Code that two games need lives in an addon:",
         "find the addon below (or add the base class to the closest one), put the shared code there,",
         "and have each game extend it (`extends DotXxx`, override the hooks). Bump the addon's API",
         "LEVEL and the game's requires.floor.json when the game uses the new API. A new addon only",
         "when none fits. The pre-push gate (check-duplication.py --siblings) refuses new code a game",
         "shares with another game.",
         "",
         "| Addon | API | What it is for |",
         "|---|---|---|"]
    for x in rows:
        w.append("| %s (`addons/%s`) | %s | %s |" % (x["name"], x["dir"], x["level"] or "-", x["desc"].replace("|", "/")))
    w.append("")
    w.append("## Classes to extend, per addon")
    for x in rows:
        if not x["classes"]:
            continue
        w.append("")
        w.append("### %s" % x["name"])
        for c, f, doc in x["classes"]:
            w.append("- `%s` %s%s" % (c, f, (" - " + doc[:160]) if doc else ""))
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(w) + "\n")
    print("wrote %s (%d addons, %d classes)" % (out, len(rows), sum(len(x["classes"]) for x in rows)))


if __name__ == "__main__":
    main()
